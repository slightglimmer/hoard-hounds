const { chromium } = require(process.env.PLAYWRIGHT || 'playwright');
const S = process.argv[2] || require('os').tmpdir() + '/hh-test-output'; const BASE = 'http://localhost:5180/admin/';
const ok = (c, m) => console.log((c ? 'PASS ' : 'FAIL ') + m);
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
  await ctx.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: 'http://localhost:5180' });
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
  const dialog = p.getByRole('dialog');
  await p.goto(BASE + '#/jobs', { waitUntil: 'networkidle' }); await p.waitForTimeout(800);
  await p.locator('main ul li a[href^="#/jobs/"]').filter({ hasText: 'Scheduled' }).first().click(); await p.waitForTimeout(1000);
  const sum = () => p.getByRole('complementary', { name: 'Job money summary' }).textContent();
  const before = await sum();
  ok(await p.getByText('Online payment links').isVisible(), 'online payments panel on job');
  await p.getByRole('button', { name: 'Request online payment' }).click(); await p.waitForTimeout(300);
  await dialog.getByRole('button', { name: 'Create payment link' }).click(); await p.waitForTimeout(200);
  ok(await dialog.getByText('Enter an amount of at least $0.50.').isVisible(), 'amount required');
  await dialog.getByLabel('Amount').fill('250');
  await dialog.getByRole('button', { name: 'Create payment link' }).click(); await p.waitForTimeout(900);
  ok(await dialog.getByRole('heading', { name: 'Payment link ready' }).isVisible() && await dialog.getByText(/buy\.stripe\.com/).isVisible(), 'link created and shown');
  await dialog.getByRole('button', { name: 'Copy message' }).click(); await p.waitForTimeout(200);
  const msg = await p.evaluate(() => navigator.clipboard.readText());
  ok(msg.includes('$250.00') && msg.includes('https://buy.stripe.com/') && msg.includes('Klarna (subject to approval)') && msg.startsWith('Hi '), 'message has amount, link, Klarna note');
  console.log('   message: ' + msg.split('\n')[0].slice(0, 120) + '…');
  const smsHref = await dialog.getByRole('link', { name: 'Text it' }).getAttribute('href');
  ok(smsHref.startsWith('sms:') && smsHref.includes('body='), 'text-message button');
  await dialog.getByRole('button', { name: 'Done' }).click(); await p.waitForTimeout(300);
  ok(await p.getByText('Waiting for customer').isVisible(), 'request listed as waiting');
  await p.screenshot({ path: S + '/shots/stripe-job.png', fullPage: true });
  await p.getByRole('button', { name: 'Pretend the customer paid (demo)' }).click(); await p.waitForTimeout(1200);
  const after = await sum();
  const received = (t) => Number(t.match(/Received\$([\d,.]+)/)[1].replace(/,/g, ''));
  ok(received(after) - received(before) === 250, `payment recorded on job automatically (+$250: ${received(before)} -> ${received(after)})`);
  ok(await p.getByText('Paid', { exact: true }).first().isVisible(), 'request shows Paid');
  // second request then cancel
  await p.getByRole('button', { name: 'Request online payment' }).click(); await p.waitForTimeout(300);
  await dialog.getByLabel('Amount').fill('75'); await dialog.getByRole('button', { name: 'Create payment link' }).click(); await p.waitForTimeout(900);
  await dialog.getByRole('button', { name: 'Done' }).click(); await p.waitForTimeout(300);
  await p.getByRole('button', { name: 'Cancel link' }).click(); await p.waitForTimeout(800);
  ok(!(await p.getByText('Waiting for customer').count()), 'cancelled link hidden');
  await p.setViewportSize({ width: 390, height: 844 }); await p.waitForTimeout(400);
  console.log('mobile overflow', await p.evaluate(() => document.documentElement.scrollWidth - innerWidth));
  console.log('errors', errs);
  await b.close();
})();
